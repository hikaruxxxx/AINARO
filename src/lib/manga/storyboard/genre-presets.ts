/**
 * 異世界なろう系 3ジャンル特化プリセット (Phase A 検証作品向け)
 *
 * Phase A の3作品並行制作で、各ジャンルのナラティブテンプレを storyboard-builder に
 * 注入するための定数集。LLM に「このジャンルの定型」を教えることで:
 *   - キャラ造形の典型パターンに収束させる (読者の期待を裏切らない)
 *   - ジャンル必須シーン (戦闘/レベルアップ/会議/突入) を欠落させない
 *   - 視覚モチーフ (剣・魔法陣・スマホ等) の繰り返しで作品個性を作る
 *
 * 使い方:
 *   buildStoryboard() の systemContext に、対応する MangaGenrePreset の
 *   `system_context_addition` を末尾に append する想定。
 *
 * 拡張方針:
 *   Phase A で売れた1ジャンルに集中する Phase B 移行時、当該ジャンルのプリセットを
 *   実績ベースで強化する。最初は本ファイルの初期値で開始。
 */

export type MangaGenreId =
  | "dungeon_exploration" // ダンジョン探索 (manga_bw_seinen_dark)
  | "noble_territory" // 転生貴族・領地経営 (manga_bw_shoujo_classic)
  | "modern_dungeon"; // 現代ダンジョン (manga_bw_seinen_urban)

export type MangaGenrePreset = {
  id: MangaGenreId;
  display_name: string;
  art_style: string;
  /** 推奨主人公パターン (1作品で1つ選ぶ) */
  protagonist_archetypes: string[];
  /** 物語の典型的構造 */
  narrative_structure: string;
  /** 1巻目に必ず入れるべきシーン群 (欠落すると読者期待を裏切る) */
  must_have_volume_1_scenes: string[];
  /** 視覚モチーフ (繰り返し描写すべき記号・小物・構図) */
  visual_motifs: string[];
  /** 引きの定型パターン (cliffhanger_hook の作法) */
  cliffhanger_patterns: string[];
  /** 想定読者層 */
  target_audience: string;
  /** 1巻 (160-200ページ) の話数構成目安 */
  recommended_episode_structure: string;
  /** storyboard-builder.ts の systemContext 末尾に追加する文字列 */
  system_context_addition: string;
};

