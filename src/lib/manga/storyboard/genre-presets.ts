export const GENRE_PRESETS: MangaGenrePreset[] = [
  dungeon_exploration,
  noble_territory,
  modern_dungeon,
];

export const GENRE_PRESETS_BY_ID: Map<MangaGenreId, MangaGenrePreset> = new Map(
  GENRE_PRESETS.map((p) => [p.id, p])
);

export function getGenrePreset(id: MangaGenreId): MangaGenrePreset | undefined {
  return GENRE_PRESETS_BY_ID.get(id);
}

/**
 * art_style から逆引き (1ジャンル1画風前提)
 */
export function findGenreByArtStyle(
  artStyle: string
): MangaGenrePreset | undefined {
  return GENRE_PRESETS.find((p) => p.art_style === artStyle);
}
